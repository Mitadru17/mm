document.addEventListener("DOMContentLoaded", () => {
  'use strict';

  const CONFIG = {
    duration: 0.5,
    ease: 'power1.out',
    storageKey: 'site-theme-preference',
    defaultTheme: 'summer',
    themes: {
      summer: 'light',
      winter: 'dark'
    }
  };

  // State
  let currentTheme = CONFIG.defaultTheme;
  
  // Store slide references with their original positions
  const slideRegistry = new Map();

  // Get elements
  const buttons = {
    summer: document.querySelector('[data-theme-button="summer"]'),
    winter: document.querySelector('[data-theme-button="winter"]')
  };

  const themeTextElements = {
    summer: document.querySelector('[data-theme-text="summer"]'),
    winter: document.querySelector('[data-theme-text="winter"]')
  };

  const imageContainers = document.querySelectorAll('[data-theme-image-wrap]');
  const htmlElement = document.documentElement;
  const bodyElement = document.body;

  const liveRegion = createLiveRegion();

  function createLiveRegion() {
    const region = document.createElement('div');
    region.setAttribute('role', 'status');
    region.setAttribute('aria-live', 'polite');
    region.setAttribute('aria-atomic', 'true');
    region.className = 'sr-only';
    region.style.cssText =
      'position:absolute;left:-10000px;width:1px;height:1px;overflow:hidden;';
    document.body.appendChild(region);
    return region;
  }

  function announce(message) {
    liveRegion.textContent = message;
  }

  function getSavedTheme() {
    try {
      return localStorage.getItem(CONFIG.storageKey) || CONFIG.defaultTheme;
    } catch (e) {
      console.warn('LocalStorage not available:', e);
      return CONFIG.defaultTheme;
    }
  }

  function saveTheme(theme) {
    try {
      localStorage.setItem(CONFIG.storageKey, theme);
    } catch (e) {
      console.warn('Could not save theme preference:', e);
    }
  }

  function updateThemeText(toTheme) {
    const { summer, winter } = themeTextElements;
    
    if (!summer || !winter) return;

    // Update aria-hidden for screen readers
    summer.setAttribute('aria-hidden', toTheme !== 'summer');
    winter.setAttribute('aria-hidden', toTheme !== 'winter');

    if (typeof gsap !== 'undefined') {
      if (toTheme === 'summer') {
        gsap.to(winter, { opacity: 0, duration: CONFIG.duration, ease: CONFIG.ease });
        gsap.to(summer, { opacity: 1, duration: CONFIG.duration, ease: CONFIG.ease });
      } else {
        gsap.to(summer, { opacity: 0, duration: CONFIG.duration, ease: CONFIG.ease });
        gsap.to(winter, { opacity: 1, duration: CONFIG.duration, ease: CONFIG.ease });
      }
    } else {
      summer.style.opacity = toTheme === 'summer' ? '1' : '0';
      winter.style.opacity = toTheme === 'winter' ? '1' : '0';
    }
  }

  function initializeThemeText() {
    const { summer, winter } = themeTextElements;
    
    if (!summer || !winter) return;

    summer.style.opacity = currentTheme === 'summer' ? '1' : '0';
    winter.style.opacity = currentTheme === 'winter' ? '1' : '0';
    
    summer.setAttribute('aria-hidden', currentTheme !== 'summer');
    winter.setAttribute('aria-hidden', currentTheme !== 'winter');
  }

  function updateButtonStates(activeTheme) {
    Object.keys(buttons).forEach(theme => {
      const button = buttons[theme];
      if (!button) return;

      const isActive = theme === activeTheme;

      button.classList.remove('is-active');

      requestAnimationFrame(() => {
        button.classList.toggle('is-active', isActive);
        button.setAttribute('aria-pressed', isActive);
      });
    });
  }

  function updateThemeClasses(theme) {
    bodyElement.classList.remove('u-theme-light', 'u-theme-dark');

    const themeClass = `u-theme-${CONFIG.themes[theme]}`;
    bodyElement.classList.add(themeClass);

    htmlElement.setAttribute('data-theme', theme);
  }

  function animateThemeColors(toTheme) {
    if (typeof gsap === 'undefined' || typeof colorThemes === 'undefined') {
      console.warn('GSAP or colorThemes not available');
      return;
    }

    const themeColors = colorThemes.getTheme(CONFIG.themes[toTheme]);

    gsap.to('body', {
      ...themeColors,
      duration: CONFIG.duration,
      ease: CONFIG.ease
    });
  }

  function switchImages(toTheme) {
    if (typeof gsap === 'undefined') {
      console.warn('GSAP not loaded. Images will switch without animation.');
      switchImagesWithoutGSAP(toTheme);
      return;
    }

    imageContainers.forEach(container => {
      const summerImg = container.querySelector('[data-theme-image-summer]');
      const winterImg = container.querySelector('[data-theme-image-winter]');

      if (!summerImg || !winterImg) {
        console.warn('Theme images not found in container:', container);
        return;
      }

      if (toTheme === 'summer') {
        gsap.to(winterImg, {
          opacity: 0,
          duration: CONFIG.duration,
          ease: CONFIG.ease
        });
        gsap.to(summerImg, {
          opacity: 1,
          duration: CONFIG.duration,
          ease: CONFIG.ease
        });
      } else {
        gsap.to(summerImg, {
          opacity: 0,
          duration: CONFIG.duration,
          ease: CONFIG.ease
        });
        gsap.to(winterImg, {
          opacity: 1,
          duration: CONFIG.duration,
          ease: CONFIG.ease
        });
      }
    });
  }

  function switchImagesWithoutGSAP(toTheme) {
    imageContainers.forEach(container => {
      const summerImg = container.querySelector('[data-theme-image-summer]');
      const winterImg = container.querySelector('[data-theme-image-winter]');

      if (!summerImg || !winterImg) return;

      if (toTheme === 'summer') {
        winterImg.style.opacity = '0';
        summerImg.style.opacity = '1';
      } else {
        summerImg.style.opacity = '0';
        winterImg.style.opacity = '1';
      }
    });
  }

  function registerSlides() {
    const sliderWrappers = document.querySelectorAll('[data-smooothy]');
    
    sliderWrappers.forEach(wrapper => {
      const slides = Array.from(wrapper.children);
      
      slides.forEach((slide, index) => {
        const slideTheme = slide.getAttribute('data-theme-slide');
        
        if (slideTheme && slideTheme !== 'both') {
          const slideId = `${wrapper.getAttribute('data-smooothy')}-${index}`;
          slideRegistry.set(slideId, {
            element: slide,
            parent: wrapper,
            theme: slideTheme,
            nextSibling: slide.nextSibling,
            index: index
          });
        }
      });
    });
  }

  function updateSlideVisibility(toTheme, animate = true) {
    if (slideRegistry.size === 0) return;

    const slidesToRemove = [];
    const slidesToAdd = [];

    slideRegistry.forEach((slideInfo, slideId) => {
      const shouldShow = slideInfo.theme === toTheme;
      const isCurrentlyInDOM = slideInfo.element.parentNode !== null;

      if (shouldShow && !isCurrentlyInDOM) {
        slidesToAdd.push(slideInfo);
      } else if (!shouldShow && isCurrentlyInDOM) {
        slidesToRemove.push(slideInfo);
      }
    });

    if (slidesToRemove.length > 0) {
      if (typeof gsap !== 'undefined' && animate) {
        gsap.to(slidesToRemove.map(s => s.element), {
          opacity: 0,
          duration: CONFIG.duration,
          ease: CONFIG.ease,
          onComplete: () => {
            slidesToRemove.forEach(slideInfo => {
              if (slideInfo.element.parentNode) {
                slideInfo.element.remove();
              }
            });
            
            addSlides(slidesToAdd, animate);
          }
        });
      } else {
        slidesToRemove.forEach(slideInfo => {
          if (slideInfo.element.parentNode) {
            slideInfo.element.remove();
          }
        });
        addSlides(slidesToAdd, animate);
      }
    } else {
      addSlides(slidesToAdd, animate);
    }
  }

  function addSlides(slidesToAdd, animate) {
    if (slidesToAdd.length === 0) {
      setTimeout(() => {
        document.dispatchEvent(new CustomEvent('reinitializeSliders'));
      }, 50);
      return;
    }

    const slidesByParent = new Map();
    slidesToAdd.forEach(slideInfo => {
      if (!slidesByParent.has(slideInfo.parent)) {
        slidesByParent.set(slideInfo.parent, []);
      }
      slidesByParent.get(slideInfo.parent).push(slideInfo);
    });

    slidesByParent.forEach((slides, parent) => {
      slides.sort((a, b) => a.index - b.index);
      
      slides.forEach(slideInfo => {
        const allSlidesInOrder = Array.from(slideRegistry.values())
          .filter(s => s.parent === parent)
          .sort((a, b) => a.index - b.index);
        
        let insertBeforeNode = null;
        for (let i = slideInfo.index + 1; i < allSlidesInOrder.length; i++) {
          const nextSlide = allSlidesInOrder.find(s => s.index === i);
          if (nextSlide && nextSlide.element.parentNode) {
            insertBeforeNode = nextSlide.element;
            break;
          }
        }
        
        if (insertBeforeNode) {
          parent.insertBefore(slideInfo.element, insertBeforeNode);
        } else {
          parent.appendChild(slideInfo.element);
        }
      });
    });

    if (typeof gsap !== 'undefined' && animate) {
      gsap.fromTo(slidesToAdd.map(s => s.element),
        { opacity: 0 },
        {
          opacity: 1,
          duration: CONFIG.duration,
          ease: CONFIG.ease,
          onComplete: () => {
            document.dispatchEvent(new CustomEvent('reinitializeSliders'));
          }
        }
      );
    } else {
      slidesToAdd.forEach(slideInfo => {
        slideInfo.element.style.opacity = '1';
      });
      setTimeout(() => {
        document.dispatchEvent(new CustomEvent('reinitializeSliders'));
      }, 50);
    }
  }

  function setTheme(theme, shouldAnnounce = true, animate = true) {
    if (!CONFIG.themes[theme]) {
      console.error(`Invalid theme: ${theme}`);
      return;
    }

    currentTheme = theme;

    updateThemeClasses(theme);

    if (animate) {
      animateThemeColors(theme);
    } else {
      if (typeof colorThemes !== 'undefined') {
        gsap.set('body', colorThemes.getTheme(CONFIG.themes[theme]));
      }
    }

    updateButtonStates(theme);
    updateThemeText(theme);
    switchImages(theme);
    updateSlideVisibility(theme, animate);
    saveTheme(theme);

    if (shouldAnnounce) {
      const themeName = theme.charAt(0).toUpperCase() + theme.slice(1);
      announce(`${themeName} theme activated`);
    }
  }

  function initializeImages() {
    imageContainers.forEach(container => {
      const summerImg = container.querySelector('[data-theme-image-summer]');
      const winterImg = container.querySelector('[data-theme-image-winter]');

      if (!summerImg || !winterImg) return;

      if (currentTheme === 'summer') {
        summerImg.style.opacity = '1';
        winterImg.style.opacity = '0';
      } else {
        summerImg.style.opacity = '0';
        winterImg.style.opacity = '1';
      }
    });
  }

  function initializeSlides() {
    registerSlides();
    
    slideRegistry.forEach((slideInfo) => {
      if (slideInfo.theme !== currentTheme && slideInfo.element.parentNode) {
        slideInfo.element.remove();
      }
    });
  }

  function setupEventListeners() {
    Object.keys(buttons).forEach(theme => {
      const button = buttons[theme];
      if (!button) {
        console.warn(`Button for ${theme} theme not found`);
        return;
      }

      button.addEventListener('click', () => {
        if (currentTheme !== theme) {
          setTheme(theme, true, true);
        }
      });

      button.addEventListener('keydown', (e) => {
        if (e.key === 'Enter' || e.key === ' ') {
          e.preventDefault();
          if (currentTheme !== theme) {
            setTheme(theme, true, true);
          }
        }
      });
    });
  }

  function init() {
    currentTheme = getSavedTheme();

    initializeImages();
    initializeThemeText();
    initializeSlides();

    updateThemeClasses(currentTheme);

    if (typeof colorThemes !== 'undefined' && typeof gsap !== 'undefined') {
      gsap.set('body', colorThemes.getTheme(CONFIG.themes[currentTheme]));
    }

    updateButtonStates(currentTheme);

    setupEventListeners();
    
    document.dispatchEvent(new CustomEvent('colorThemesReady'));
  }

  init();
});


