const { chromium } = require('../.codex/qa/node_modules/playwright');
(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.on('pageerror', error => console.log('ERROR', error.message));
  await page.goto('http://localhost:4174/', { waitUntil: 'networkidle' });
  await page.locator('.arrival-hero[data-phase=ready]').waitFor();
  await page.getByRole('button', { name: 'Open navigation', exact: true }).click();
  await page.waitForTimeout(180);
  await page.screenshot({ path: 'docs/client-polish/menu-enter.jpg' });
  await page.locator('.site-menu[data-phase=open]').waitFor();
  await page.screenshot({ path: 'docs/client-polish/menu-desktop.jpg' });
  await page.getByRole('button', { name: 'Close navigation', exact: true }).click();
  await page.waitForFunction(() => !document.querySelector('.site-menu').open);
  await page.getByRole('button', { name: 'Enquire about your stay', exact: true }).click();
  await page.waitForTimeout(450);
  await page.screenshot({ path: 'docs/client-polish/planner.jpg' });
  await page.keyboard.press('Escape');
  await page.waitForFunction(() => !document.querySelector('.jh-booking-modal'));
  await page.goto('http://localhost:4174/#stay', { waitUntil: 'networkidle' });
  await page.waitForTimeout(1500);
  await page.screenshot({ path: 'docs/client-polish/editorial.jpg' });
  await page.goto('http://localhost:4174/#contact', { waitUntil: 'networkidle' });
  await page.waitForTimeout(1600);
  await page.screenshot({ path: 'docs/client-polish/footer.jpg' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Open navigation', exact: true }).click();
  await page.locator('.site-menu[data-phase=open]').waitFor();
  await page.screenshot({ path: 'docs/client-polish/menu-phone.jpg' });
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
