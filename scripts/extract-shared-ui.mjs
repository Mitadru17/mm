import postcss from "postcss";
import { readFile, writeFile } from "node:fs/promises";

// Preserve the tested inquiry/dialog/image interfaces while replacing page composition.
const allowed =
  /\.(?:image-shell|image-skeleton|image-error|skeleton|button(?:-|\b)|icon-button|modal(?:-|\b)|close-button|lightbox(?:-|\b)|inquiry(?:-|\b)|preference-label|fine-print|room-modal(?:-|\b)|room-photo-controls|booking(?:-|\b)|date-field|guest-fields|contact-fields|special-requests|form-error|model-skeleton|art-modal|motion-preference|sr-only)/;
const output = postcss.root();
function filter(node) {
  if (node.type === "rule") {
    const selectors = node.selectors.filter(
      (selector) => allowed.test(selector) || selector === ":root",
    );
    return selectors.length
      ? node.clone({ selector: selectors.join(",") })
      : null;
  }
  if (node.type === "atrule" && node.name === "keyframes")
    return node.params === "shimmer" ? node.clone() : null;
  if (node.type === "atrule" && node.nodes) {
    const children = node.nodes.map(filter).filter(Boolean);
    return children.length ? node.clone({ nodes: children }) : null;
  }
  return null;
}
for (const file of [
  "src/styles.css",
  "src/responsive.css",
  "src/cinematic.css",
]) {
  const root = postcss.parse(await readFile(file, "utf8"));
  root.nodes
    .map(filter)
    .filter(Boolean)
    .forEach((node) => output.append(node));
}
await writeFile(
  "src/tidescape/shared-ui.css",
  "/* Retained inquiry, image and dialog styling. Generated by scripts/extract-shared-ui.mjs. */\n" +
    output.toString(),
);
